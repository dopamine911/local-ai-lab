#!/usr/bin/env bash
# Write hub/openwebui/comfyui.env (loaded by compose.yaml for open-webui) from a ComfyUI workflow file, so the workflow
# file stays the only copy. Run after changing the workflow or switching models; then: drift.sh --sync.
#   hub/openwebui/make-comfyui-env.sh            Z-Image Turbo (default: 5 s per 1024px image, steps adjustable)
#   hub/openwebui/make-comfyui-env.sh qwen       Qwen-Image 2.1 Turbo (6 s; best at text inside images; steps fixed)
# Node numbers: hub/comfyui/workflows/*.json and README "Open WebUI settings".
set -euo pipefail
cd "$(dirname "$0")/.."
case "${1:-zimage}" in
  zimage) WF=comfyui/workflows/z-image-turbo-api.json; MODEL=z_image_turbo_bf16.safetensors
    NODES='[{"type":"model","key":"unet_name","node_ids":["1"]},{"type":"prompt","key":"text","node_ids":["5"]},{"type":"width","key":"width","node_ids":["7"]},{"type":"height","key":"height","node_ids":["7"]},{"type":"steps","key":"steps","node_ids":["8"]},{"type":"seed","key":"seed","node_ids":["8"]}]' ;;
  qwen) WF=comfyui/workflows/qwen-image-2.1-turbo-api.json; MODEL=qwen_image_2.1_turbo_int8_convrot.safetensors
    NODES='[{"type":"model","key":"unet_name","node_ids":["1"]},{"type":"prompt","key":"prompt","node_ids":["5"]},{"type":"width","key":"width","node_ids":["6"]},{"type":"height","key":"height","node_ids":["6"]},{"type":"seed","key":"noise_seed","node_ids":["7"]}]' ;;
  *) sed -n '2,7p' "$0"; exit 1 ;;
esac
{
  echo "# GENERATED by openwebui/make-comfyui-env.sh from $WF. Do not edit by hand."
  echo "IMAGE_GENERATION_MODEL=$MODEL"
  echo "COMFYUI_WORKFLOW_NODES=$NODES"
  echo "COMFYUI_WORKFLOW=$(python3 -c 'import json,sys;print(json.dumps(json.load(open(sys.argv[1])),separators=(",",":")))' "$WF")"
} > openwebui/comfyui.env
grep -q '\$' openwebui/comfyui.env && { echo "workflow contains \$, which compose would treat as a variable"; exit 1; }
echo "openwebui/comfyui.env written from $WF ($(wc -c < openwebui/comfyui.env) bytes)"
