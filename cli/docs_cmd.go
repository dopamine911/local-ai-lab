package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
)

// docsCmd writes the command reference (docs/cli/) from the commands' own help text, so the reference can't say
// something lab doesn't do. Output is deterministic (cobra sorts commands; no dates), so it only changes when the help
// changes; cli/build.sh regenerates it and warns when the committed copy is out of date. Hidden: a tool for the repo.
func docsCmd(root *cobra.Command) *cobra.Command {
	return &cobra.Command{
		Use:    "docs <folder>",
		Short:  "Write the command reference (Markdown, one page per command) into a folder",
		Hidden: true,
		Args:   cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			dir := args[0]
			if err := os.MkdirAll(dir, 0o755); err != nil {
				return err
			}
			old, _ := filepath.Glob(filepath.Join(dir, "*.md")) // pages of removed commands go too
			for _, f := range old {
				os.Remove(f)
			}
			var idx strings.Builder
			idx.WriteString(header("lab: command reference"))
			idx.WriteString("One CLI for the lab (issue #6). `lab` on a terminal opens a menu; `lab <command> --help` shows the same\n" +
				"text as these pages. Config: `cli/lab.yaml`; secrets stay in the `.env` files and are never printed.\n\n")
			idx.WriteString("| Command | What it does |\n| --- | --- |\n")
			for _, c := range visible(root) {
				idx.WriteString(fmt.Sprintf("| [`lab %s`](%s.md) | %s |\n", c.Name(), c.Name(), cell(c.Short)))
				var b strings.Builder
				b.WriteString(header("lab " + c.Name()))
				page(&b, c, 2)
				if err := os.WriteFile(filepath.Join(dir, c.Name()+".md"), []byte(b.String()), 0o644); err != nil {
					return err
				}
			}
			return os.WriteFile(filepath.Join(dir, "README.md"), []byte(idx.String()), 0o644)
		},
	}
}

func header(title string) string {
	return "# " + title + "\n\n<!-- Generated by `lab docs` from the commands' own help (cli/build.sh). Do not edit by hand:\n" +
		"     change the command's help text in cli/ and rebuild. -->\n\n"
}

// visible: the commands a person can run (not help, completion or hidden ones), in cobra's sorted order.
func visible(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range c.Commands() {
		if s.IsAvailableCommand() && s.Name() != "help" && s.Name() != "completion" {
			out = append(out, s)
		}
	}
	return out
}

// page writes one command and, below it, each of its subcommands one heading level deeper.
func page(b *strings.Builder, c *cobra.Command, level int) {
	text := c.Long
	if text == "" {
		text = c.Short
	}
	// The help is written for a terminal (line breaks, indented examples): kept as plain text, as --help shows it.
	b.WriteString("```text\n" + strings.TrimRight(text, "\n") + "\n```\n\n")
	use := strings.TrimSpace(c.UseLine())
	if len(visible(c)) > 0 && !c.Runnable() {
		use += " <command>"
	}
	b.WriteString("Usage:\n\n```\n" + use + "\n```\n\n")
	var opts []string // without -h/--help: every command has it, and cobra adds it only to the command that runs
	for _, l := range strings.Split(strings.TrimRight(c.NonInheritedFlags().FlagUsages(), "\n"), "\n") {
		if l != "" && !strings.Contains(l, "--help") {
			opts = append(opts, l)
		}
	}
	if len(opts) > 0 && !c.DisableFlagParsing {
		b.WriteString("Options:\n\n```\n" + strings.Join(opts, "\n") + "\n```\n\n")
	}
	for _, s := range visible(c) {
		b.WriteString(strings.Repeat("#", level) + " lab " + strings.TrimPrefix(s.CommandPath(), "lab ") + "\n\n")
		page(b, s, level+1)
	}
}

// cell makes a one-line help text safe inside a Markdown table.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
