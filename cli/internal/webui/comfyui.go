// comfyWorkflows: the image workflows Open WebUI can use through ComfyUI (hub/comfyui/workflows), with the node
// numbers Open WebUI fills in (README "Open WebUI settings").
var comfyWorkflows = map[string]struct{ file, model, nodes string }{
	"zimage": {"comfyui/workflows/z-image-turbo-api.json", "z_image_turbo_bf16.safetensors",
		`[{"type":"model","key":"unet_name","node_ids":["1"]},{"type":"prompt","key":"text","node_ids":["5"]},{"type":"width","key":"width","node_ids":["7"]},{"type":"height","key":"height","node_ids":["7"]},{"type":"steps","key":"steps","node_ids":["8"]},{"type":"seed","key":"seed","node_ids":["8"]}]`},
	"qwen": {"comfyui/workflows/qwen-image-2.1-turbo-api.json", "qwen_image_2.1_turbo_int8_convrot.safetensors",
		`[{"type":"model","key":"unet_name","node_ids":["1"]},{"type":"prompt","key":"prompt","node_ids":["5"]},{"type":"width","key":"width","node_ids":["6"]},{"type":"height","key":"height","node_ids":["6"]},{"type":"seed","key":"noise_seed","node_ids":["7"]}]`},
}

// ComfyEnv is `lab webui comfyui-env [zimage|qwen]` (port of hub/openwebui/make-comfyui-env.sh): writes
// hub/openwebui/comfyui.env (loaded by compose for open-webui) from a ComfyUI workflow file, so the workflow file
// stays the only copy. Then `lab webui drift --sync`.
func ComfyEnv(hub, which string) (string, error) {
	w, ok := comfyWorkflows[which]
	if !ok {
		return "", fmt.Errorf("unknown workflow %q (zimage or qwen)", which)
	}
	raw, err := os.ReadFile(filepath.Join(hub, w.file))
	if err != nil {
		return "", err
	}
	compact, err := pyCompactJSON(raw)
	if err != nil {
		return "", fmt.Errorf("%s: %v", w.file, err)
	}
	text := "# GENERATED by openwebui/make-comfyui-env.sh from " + w.file + ". Do not edit by hand.\n" +
		"IMAGE_GENERATION_MODEL=" + w.model + "\n" +
		"COMFYUI_WORKFLOW_NODES=" + w.nodes + "\n" +
		"COMFYUI_WORKFLOW=" + compact + "\n"
	out := filepath.Join(hub, "openwebui", "comfyui.env")
	if err := os.WriteFile(out, []byte(text), 0o644); err != nil {
		return "", err
	}
	if strings.Contains(text, "$") {
		return "", fmt.Errorf("workflow contains $, which compose would treat as a variable")
	}
	return fmt.Sprintf("openwebui/comfyui.env written from %s (%d bytes)", w.file, len(text)), nil
}

// pyCompactJSON gives what the script's json.dumps(json.load(f), separators=(",",":")) did: keys in file order,
// no spaces, non-ASCII escaped as \uXXXX (ensure_ascii), no HTML escaping.
func pyCompactJSON(raw []byte) (string, error) {
	var b bytes.Buffer
	if err := json.Compact(&b, raw); err != nil {
		return "", err
	}
	var s strings.Builder
	for _, r := range b.String() {
		switch {
		case r < 0x80:
			s.WriteRune(r)
		case r <= 0xFFFF:
			fmt.Fprintf(&s, `\u%04x`, r)
		default: // surrogate pair, as Python writes it
			r -= 0x10000
			fmt.Fprintf(&s, `\u%04x\u%04x`, 0xD800+(r>>10), 0xDC00+(r&0x3FF))
		}
	}
	return s.String(), nil
}
